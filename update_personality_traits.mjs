async function updatePersonalityTraits() {
  const db = drizzle(process.env.DATABASE_URL);
  
  console.log("開始更新塔羅牌性格特質...");
  
  for (const card of personalityTraits) {
    try {
      await db.update(tarotCards)
        .set({
          positiveTraits: card.positiveTraits,
          negativeTraits: card.negativeTraits
        })
        .where(eq(tarotCards.id, card.id));
      
      console.log(`✓ 已更新 ${card.id} - ${card.name}`);
    } catch (error) {
      console.error(`✗ 更新失敗 ${card.id} - ${card.name}:`, error);
    }
  }
  
  console.log("\n更新完成！");
  process.exit(0);
}

updatePersonalityTraits().catch(error => {
  console.error("執行錯誤:", error);
  process.exit(1);
});
