async function updateScriptAnalysis() {
  const db = drizzle(process.env.DATABASE_URL);
  
  console.log("開始更新塔羅牌運勢劇本解析...");
  
  for (const card of scriptAnalysisData) {
    try {
      await db.update(tarotCards)
        .set({
          scriptAnalysis: card.scriptAnalysis
        })
        .where(eq(tarotCards.id, card.id));
      
      console.log(`✓ 已更新 ${card.id} - ${card.name}`);
    } catch (error) {
      console.error(`✗ 更新失敗 ${card.id} - ${card.name}:`, error);
    }
  }
  
  console.log("\n更新完成！");
  process.exit(0);
}

updateScriptAnalysis().catch(error => {
  console.error("執行錯誤:", error);
  process.exit(1);
});
